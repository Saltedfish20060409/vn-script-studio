"""改写契约：改稿时"不许靠删掉来变干净"的硬约束。

它要解决的问题
--------------
改稿链路每一级都在做减法（诊断标 cut → 规则删说明书段 → 缝合跳切 → 必要时压缩），而
`chapter_revise.REWRITE_SYSTEM` 第 101 行曾用**好戏里的台词**当反例：

    **禁止**工序/常识百科问答（为什么要分开、什么时候放、原理就是…）

那两句正是那顿晚饭里雪菜的问话，于是整场戏被归类成"工序百科问答"、当成 `cut` 项删掉。
叠加"零硬错误才准定稿"的门禁，**删掉**成了消除违规最省事的做法——第一章实测就是这个结果：
该禁的都禁了，戏也没了。

所以这里给改稿侧一条压过其余条文的硬契约：违规**就地改写**，信息**只增不减**。

它为什么单独成一个模块
----------------------
这份契约原先和「声口范例库」（生成侧的正向范例）一起放在 `voice_bible.py` 里。
2026-10 决定**删掉范例库整块**：它的四条"声口指令"与 `writing_craft` 里已有的技能
逐条重复（`silence_beat` / `talk_economy` / `anti_qa_pingpong` / `subtext_conflict` /
`pacing_hook` 已经说了同样的话），而七个范例的不可替代性只在于"冷启动时没有别的样例可给"——
那件事的正确来源是作者自己的定稿（`styleMemory.samples` 与 `characters[].voiceCorpus`
两套已有机制），不是流水线里手写的一段散文。

契约与范例库是两回事：范例是**偏好**（可以有、可以没有、可以换成作者的），
契约是**正确性**（删掉内容不是"另一种写法"，是丢信息）。所以范例库删掉，契约留下。
"""
from __future__ import annotations

REWRITE_CONTRACT = """【改写契约（改稿/修正专用，优先级高于本页其余条文）】

1. **违规就地改写，不许靠删掉来变干净。** 删掉一句不算改好；删掉一件事更不算。
2. 就地改写就这四种换法，按情况挑一个：
   - 讲解 → 经过（把说明变成"发生了一件事"）
   - 心理标签 → 动作 / 停顿 / 视线（"他愣了一下" → "他手上的动作停了一下"）
   - 套话形容词 → 具体物象（"心里一暖" → "他把外套挂在了门口的挂钩上"）
   - 对仗金句 → 一件没做完的事
3. **信息只增不减**：改完的稿子必须至少保住原稿的这些——
   物象数、关系触发、已埋伏笔、没被回答的问题、男主主动做过的、不需要解释的事。
4. 允许删的只有三类：重复语、空转形容词、作者自己的总结句。
5. 若某条规则与"保住信息"冲突，**保住信息优先**，并在改动说明里写明这处冲突。
6. 输出：改后的全文 + 逐条改动清单（哪条规则 / 改前 → 改后 / 为什么不是删掉）。"""


def rewrite_contract_block() -> str:
    """改稿侧要注入的那一段。"""
    return REWRITE_CONTRACT
