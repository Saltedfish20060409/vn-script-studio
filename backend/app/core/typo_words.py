#: (错写, 通常写法, 类型)
WORD_CONFUSIONS: List[tuple] = [
    *((wrong, right, "成语") for wrong, right in IDIOMS),
    *((wrong, right, "固定搭配") for wrong, right in FIXED),
]


def find_word_confusions(text: str) -> List[Dict[str, object]]:
    """扫一遍文本，返回所有命中的别字（按位置排序）。

    与前端同一个口径：命中即报，不做任何"看语境"的判断——词表本身已经排除了
    语境依赖的情形，这是它能做到零误报的前提。
    """
    if not text:
        return []
    hits: List[Dict[str, object]] = []
    for wrong, right, kind in WORD_CONFUSIONS:
        start = text.find(wrong)
        while start >= 0:
            hits.append(
                {
                    "wrong": wrong,
                    "right": right,
                    "kind": kind,
                    "offset": start,
                }
            )
            start = text.find(wrong, start + len(wrong))
    hits.sort(key=lambda h: (int(h["offset"]), len(str(h["wrong"]))))
    return hits


def line_of(text: str, offset: int) -> int:
    """命中位置落在第几行（1 起算）——作者要照着行号去改。"""
    if offset <= 0:
        return 1
    return text.count("\n", 0, offset) + 1
