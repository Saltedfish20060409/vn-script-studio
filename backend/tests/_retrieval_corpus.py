@dataclass
class EvalRow:
    question: str
    expected: set
    hit: set
    ok: bool


def evaluate(context_fn, *, strip_aliases: bool = False, strip_keywords: bool = False,
             questions: List[tuple] | None = None) -> List[EvalRow]:
    """跑一遍评测：对每个问题看"期望条目有没有进上下文"。

    strip_* 用来做前后对比：把别名/触发词拿掉，就是"加这些机制之前"的行为。
    """
    from app.core.project import normalize_project

    raw = build_project()
    if strip_aliases:
        for c in raw["characters"]:
            c.pop("aliases", None)
        for l in raw["locations"]:
            l.pop("aliases", None)
    if strip_keywords:
        for e in raw["loreEntries"]:
            e.pop("keywords", None)
    project = normalize_project(raw)

    # 判定要用**正文**探针，不能用标题：未命中的条目会以标题形式出现在上下文末尾的
    # "可点名"提示里，拿标题当命中信号会假通过。角色的主名则可以直接查（提示里只有条目标题）。
    probes: Dict[str, str] = {}
    for e in raw["loreEntries"]:
        body = str(e.get("body") or "").strip()
        probes[str(e.get("title") or "")] = body[:14] if body else str(e.get("title") or "")

    rows: List[EvalRow] = []
    for question, expected in questions if questions is not None else QUESTIONS:
        text = context_fn(project, question)
        hit = {t for t in expected if probes.get(t, t) and probes.get(t, t) in text}
        rows.append(EvalRow(question, set(expected), hit, bool(hit)))
    return rows
