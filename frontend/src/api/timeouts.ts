/**
 * 请求超时预算的唯一真源（前端）。
 *
 * ## 为什么要有这个文件
 *
 * 此前 134 个调用点里只有 36 个显式设了超时，其余全部落到 `http.ts` 的 30s 默认值；
 * 而这 36 个里的数字（90/120/180/240/600 秒）与后端的预算没有任何对应关系。
 * 两边的"时间"根本不是同一件事：
 *
 * - 后端写的是「**一次** LLM 调用的上限」（`app/core/llm_budget.py`）；
 * - 前端写的是「**这个 HTTP 请求**总共等多久」。
 *
 * 于是一整类端点满足 `前端预算 < 后端最坏耗时`：前端先掐断，用户看到
 * 「请确认后端服务已启动」，而**后端明明活着**、只是模型慢（慢思考模型尤其如此）。
 * `/brainstorm` 最极端：前端 30s，后端是「2–3 位作家并发 + 责编综合」两次串行调用。
 *
 * ## 三条规则（`timeouts.test.ts` 会强制校验）
 *
 * 1. **凡是会在请求内调用模型的端点，必须显式选一档预算**，不许吃 30s 默认值。
 * 2. **前端预算 ≥ 后端最坏耗时 + 余量**——余量是为了让"后端自己的如实报错"先到，
 *    而不是让前端抢先翻译成误导文案。
 * 3. **只有数字在这里**：其它文件一律引用 `TIMEOUTS.*`，不许再写裸数字。
 *
 * ## 多轮端点走作业，不靠"把预算调大"
 *
 * 两轮以上的串行调用（头脑风暴、章节回炉）最坏耗时能到 8 分钟量级，让前端干等
 * 既浪费又容易误判。它们应当**作业化**：请求只登记作业（`async_mode: true`，用最短的一档），
 * 进度与结果走 `waitProjectJob` 轮询（`JOB_POLL_TIMEOUT_MS`，不受 HTTP 超时约束）。
 * `timeouts.test.ts` 里 `mode: "job"` 的那几条就是在钉这件事——预算回到"登记"这一档，
 * 并额外要求调用点真的带 `async_mode: true`、后端真的注册了对应作业 kind。
 * （同步路径仍然保留给 API 客户端，那条仍按轮次算预算。）
 *
 * 慢思考档（`*-think`）后端会自动加时（见 `llm_budget.thinking_factor`，默认 ×2），
 * 所以这里的预算按**思考档**的最坏耗时来定——前端不知道用户此刻选的是哪一个档位，
 * 只能按最慢的算。代价是非思考档下"卡住"要多等一会儿才报错；这是有意的取舍：
 * 宁可多等，也不要在结果其实已经生成好时把连接掐掉。
 *
 * 流式路径（Agent / 管线 / 协作）**不设总超时**：它们靠心跳保活，用"多久没有新字节"
 * 判定死亡（见 `api/projects.ts` 的 `onActivity`）。给流式设总超时会重新引入同一类 bug。
 */

/** 预算阶梯（毫秒）。命名含义 = 「一次这类请求最多等多久」。 */
export const TIMEOUTS = {
  /** 非 LLM 的普通读写（列表、保存、状态查询）。 */
  fast: 30_000,
  /** 设置页「测试连接」：后端 `PROBE`=30s，思考档 ×2 = 60s。 */
  probe: 120_000,
  /**
   * 不调模型但可能搬大数据/等外部服务的一次性动作：上传、导入、快照、应用改动，
   * 以及会去外部百科取数的设定检索（后端对它有 25s 的连接超时，30s 默认值太紧）。
   */
  upload: 180_000,
  /** 一次短 LLM 调用：后端 `QUICK`=60s，思考档 120s。 */
  quick: 240_000,
  /** 一次生成型 LLM 调用：后端 `CHAT`=120s，思考档 240s。 */
  chat: 300_000,
  /** 长文写作 / 审稿 / 一致性审计：后端 `WRITE`=180s，思考档 360s。 */
  write: 480_000,
  /** 超长单轮或两轮串行：后端 `LONG`=240s（思考档 480s）、或 CHAT 两轮(480s)。 */
  long: 600_000,
  /** 多轮回炉 / 多窗口批处理：后端 `WRITE`+`LONG` 两轮，或成批窗口扫描。 */
  batch: 900_000,
} as const;

/** 后端异步作业（async job）的轮询预算：作业本身不受 HTTP 超时约束。 */
export const JOB_POLL_TIMEOUT_MS = 15 * 60_000;

/** 把毫秒说成人话，用于按钮提示 / 报错文案。 */
export function humanizeMs(ms: number): string {
  const sec = Math.round(ms / 1000);
  if (sec < 60) return `${sec} 秒`;
  const min = sec / 60;
  return Number.isInteger(min) ? `${min} 分钟` : `${min.toFixed(1)} 分钟`;
}

/**
 * 前端主动放弃（AbortController 到点）时的文案。
 *
 * 关键：**不要**说"请检查后端"——后端大概率正常，真实原因是这次调用比预算更慢。
 * 也不要说"失败了"：后台作业（自动写作 / 章节回炉）会脱离请求继续跑完，
 * 结果在运行记录里能看到；而普通同步端点会被服务端随即中止
 * （见 backend/app/core/disconnect.py），所以不要把两种情形混成一句。
 */
export function timeoutMessage(ms: number): string {
  return (
    `等待 ${humanizeMs(ms)} 仍未返回，已停止等待。` +
    `常见原因：所选模型较慢（思考档尤其慢）、本次范围偏大或上游波动。` +
    `服务端会随即停止这次生成；若是「自动写作 / 章节回炉」这类后台作业，` +
    `它会继续跑完，稍后到「运行记录」查看。也可以换非思考档、缩小范围后重试。`
  );
}

/** 连不上（DNS / 拒绝连接 / 断网 / 后端未启动）时的文案。 */
export function networkErrorMessage(): string {
  return "连接不上服务端：请检查网络，或确认后端服务/反向代理仍在运行。";
}
