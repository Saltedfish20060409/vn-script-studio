export const TYPO_RULES: readonly TypoRule[] = [
  ...IDIOMS.map(([wrong, right]) => ({ wrong, right, kind: "成语" as const })),
  ...FIXED.map(([wrong, right]) => ({ wrong, right, kind: "固定搭配" as const })),
];

export interface TypoHit {
  offset: number;
  length: number;
  wrong: string;
  right: string;
  kind: TypoKind;
}

/**
 * 扫一遍文本，返回所有命中（按位置排序）。
 *
 * 不做任何"智能"判断：命中即报。这就是零误报的前提——词表本身已经排除了语境依赖的情形。
 */
export function findTypos(text: string): TypoHit[] {
  if (!text) return [];
  const hits: TypoHit[] = [];
  for (const rule of TYPO_RULES) {
    let at = text.indexOf(rule.wrong);
    while (at >= 0) {
      hits.push({
        offset: at,
        length: rule.wrong.length,
        wrong: rule.wrong,
        right: rule.right,
        kind: rule.kind,
      });
      at = text.indexOf(rule.wrong, at + rule.wrong.length);
    }
  }
  return hits.sort((a, b) => a.offset - b.offset || a.length - b.length);
}

/** 给界面用的一句话（含建议写法）。 */
export function typoMessage(hit: TypoHit): string {
  return `疑是别字：「${hit.wrong}」通常写作「${hit.right}」（${hit.kind}）`;
}
