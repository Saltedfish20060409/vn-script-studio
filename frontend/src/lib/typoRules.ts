/**
 * 常见别字/别词（确定性词表，不调用模型、不需要词典文件）。
 *
 * 为什么是"词表"而不是"拼写检查"：中文没有分词意义上的拼写错误，真正高频、且**几乎
 * 不可能是作者本意**的，是成语与固定搭配里的同音别字（「迫不急待」「一如继往」）。
 * 这类错误的判定不需要上下文，词表就能做到**零误报**——而一个会误报的错别字提示，
 * 作者用两天就会把它整个忽略掉，比不做还糟。
 *
 * 因此收录标准极严，三条同时满足才收：
 * 1. 错写形式在中文里**不作为另一个词存在**；
 * 2. 正确形式是唯一公认写法；
 * 3. 错写形式不是某个专名、地名或角色名（否则小说里的人名地名会被误报）。
 *
 * **刻意不收**（它们同样常写错，但判定需要语境或存在异形词争议）：
 * 反应/反映、需要/须要、想象/想像、制订/制定、帐号/账号、图象/图像、份量/分量、
 * 一支/一只 等。要覆盖这些得靠模型，而不是靠猜——这里不假装能做。
 */

export type TypoKind = "成语" | "固定搭配" | "常用词";

export interface TypoRule {
  /** 错写形式 */
  wrong: string;
  /** 通常写法 */
  right: string;
  kind: TypoKind;
}

