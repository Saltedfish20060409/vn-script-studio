/** `r` ∈ [0, 1)，由调用方传入以便测试固定结果 */
export function petLine(
  key: PetLineKey,
  vars: PetLineVars = {},
  r = Math.random()
): string {
  const pool = LINES[key];
  const text = pool[Math.min(pool.length - 1, Math.floor(r * pool.length))] ?? "";
  return text.replace("{line}", vars.line === undefined ? "" : String(vars.line));
}

export function petLinePool(key: PetLineKey): readonly string[] {
  return LINES[key];
}

/** 全库句数（测试用） */
export function petLineTotal(): number {
  return (Object.keys(LINES) as PetLineKey[]).reduce((n, k) => n + LINES[k].length, 0);
}
